    CAST((CAST(TEETH AS BIGINT) * PITCH_UM) / 1000.000 AS NUMERIC(18,3))
);

ALTER TABLE DIE ADD COMPUTED_AROUND_GAP_MM COMPUTED BY (
    CAST((CAST((CAST(TEETH AS BIGINT) * PITCH_UM) / 1000.000 AS NUMERIC(18,3)) - (AROUND_UPS * AROUND_SIZE_MM)) / NULLIF(AROUND_UPS, 0) AS NUMERIC(18,3))
);

