/* =============================================================================
   DieVix – Migration V009: Flatbed Die Inventory & Directional Rules
   Target: Firebird 5.0
   Encoding: UTF8

   Description:
     1. Creates FLATBED_DIE table for tracking flatbed tooling:
        - Category: 'ROLL_FORM' (continuous rolls) or 'SHEET_FORM' (sheets/booklets)
        - Dimensions: AROUND_SIZE_MM, ACROSS_SIZE_MM, AROUND_UPS, ACROSS_UPS
        - Gaps: AROUND_GAP_MM, ACROSS_GAP_MM, CORNER_RADIUS_MM, SHAPE
        - Plate & feed limits: PLATE_WIDTH_MM, PLATE_LENGTH_MM, MAX_FEED_STROKE_MM
        - Computed Bi-directional rotation capability:
            CAN_ROTATE = 1 for ROLL_FORM with 1x1 ups OR identical around/across sizes.
            CAN_ROTATE = 0 otherwise.
     2. Creates FLATBED_DIE_AUDIT_LOG for complete lifecycle history.
     3. Creates V_FLATBED_DIE_CATALOG view for comprehensive tooling lookup.
============================================================================= */

-- 1. FLATBED_DIE Table
CREATE TABLE FLATBED_DIE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SERIAL_NO VARCHAR(30) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR(255),
    CATEGORY VARCHAR(30) NOT NULL, -- 'ROLL_FORM' or 'SHEET_FORM'
    CUSTOMER_ID INTEGER REFERENCES CUSTOMER(ID),
    MEDIA_ID INTEGER REFERENCES MEDIA(ID),
    CUSTOMER_REF VARCHAR(50),
    SUPPLIER_REF VARCHAR(50),
    INTERNAL_REF VARCHAR(50),
    
    -- Label / Cavity dimensions
    AROUND_SIZE_MM NUMERIC(9,3) NOT NULL,
    ACROSS_SIZE_MM NUMERIC(9,3) NOT NULL,
    AROUND_UPS INTEGER DEFAULT 1 NOT NULL,
    ACROSS_UPS INTEGER DEFAULT 1 NOT NULL,
    AROUND_GAP_MM NUMERIC(9,3) DEFAULT 3.000 NOT NULL,
    ACROSS_GAP_MM NUMERIC(9,3) DEFAULT 3.000 NOT NULL,
    CORNER_RADIUS_MM NUMERIC(9,3) DEFAULT 2.000 NOT NULL,
    SHAPE VARCHAR(30) DEFAULT 'RECTANGLE' NOT NULL,
    
    -- Flatbed plate & machine limits
    PLATE_WIDTH_MM NUMERIC(9,3),
    PLATE_LENGTH_MM NUMERIC(9,3),
    MAX_FEED_STROKE_MM NUMERIC(9,3),
    
    -- Computed total cutting footprint
    TOTAL_CUT_AROUND_MM COMPUTED BY ((AROUND_UPS * AROUND_SIZE_MM) + ((AROUND_UPS - 1) * AROUND_GAP_MM)),
    TOTAL_CUT_ACROSS_MM COMPUTED BY ((ACROSS_UPS * ACROSS_SIZE_MM) + ((ACROSS_UPS - 1) * ACROSS_GAP_MM)),
    
    -- Computed Bi-directional rotation rule for Rollform:
    -- 1x1 ups: bi-directional (1)
    -- Multi-ups: bi-directional ONLY IF AROUND_SIZE_MM = ACROSS_SIZE_MM (identical around & across)
    CAN_ROTATE COMPUTED BY (
        CASE
            WHEN CATEGORY = 'ROLL_FORM' AND AROUND_UPS = 1 AND ACROSS_UPS = 1 THEN 1
            WHEN CATEGORY = 'ROLL_FORM' AND AROUND_SIZE_MM = ACROSS_SIZE_MM THEN 1
            ELSE 0
        END
    ),

    -- Storage location
    STORAGE_LOCATION VARCHAR(50),
    STORAGE_RACK VARCHAR(20),
    STORAGE_SHELF VARCHAR(20),
    STORAGE_BIN VARCHAR(20),

    -- Status & Lifecycle
    STATUS_CODE VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL REFERENCES DIE_STATUS(CODE),
    PURCHASE_DATE DATE,
    RECEIVED_DATE DATE,
    DIE_MAKER VARCHAR(100),
    TOTAL_IMPRESSIONS INTEGER DEFAULT 0 NOT NULL,
    NOTES BLOB SUB_TYPE TEXT,
    
    -- Versioning & Audit
    VERSION INTEGER DEFAULT 1 NOT NULL,
    CREATED_BY VARCHAR(50) DEFAULT 'SYSTEM' NOT NULL,
    UPDATED_BY VARCHAR(50) DEFAULT 'SYSTEM' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    
    CONSTRAINT CHK_FBD_DIMS CHECK (AROUND_SIZE_MM > 0 AND ACROSS_SIZE_MM > 0),
    CONSTRAINT CHK_FBD_UPS CHECK (AROUND_UPS > 0 AND ACROSS_UPS > 0),
    CONSTRAINT CHK_FBD_CATEGORY CHECK (CATEGORY IN ('ROLL_FORM', 'SHEET_FORM'))
);

CREATE INDEX IDX_FBD_DIMS ON FLATBED_DIE (AROUND_SIZE_MM, ACROSS_SIZE_MM, AROUND_UPS, ACROSS_UPS);
CREATE INDEX IDX_FBD_CATEGORY ON FLATBED_DIE (CATEGORY);
CREATE INDEX IDX_FBD_STATUS ON FLATBED_DIE (STATUS_CODE);
CREATE INDEX IDX_FBD_CUSTOMER ON FLATBED_DIE (CUSTOMER_ID);
CREATE INDEX IDX_FBD_LOCATION ON FLATBED_DIE (STORAGE_RACK, STORAGE_SHELF, STORAGE_BIN);

-- 2. FLATBED_DIE_AUDIT_LOG Table
CREATE TABLE FLATBED_DIE_AUDIT_LOG (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FLATBED_DIE_ID INTEGER,
    DIE_SERIAL_NO VARCHAR(30),
    ACTION VARCHAR(50) NOT NULL,
    FIELD_NAME VARCHAR(50),
    OLD_VALUE VARCHAR(500),
    NEW_VALUE VARCHAR(500),
    DETAILS VARCHAR(500),
    CHANGED_BY VARCHAR(50) DEFAULT 'SYSTEM' NOT NULL,
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_FBD_AUDIT_DIE_ID ON FLATBED_DIE_AUDIT_LOG (FLATBED_DIE_ID);

-- 3. V_FLATBED_DIE_CATALOG View
CREATE OR ALTER VIEW V_FLATBED_DIE_CATALOG AS
SELECT
    F.ID,
    F.SERIAL_NO,
    F.DESCRIPTION,
    F.CATEGORY,
    F.CUSTOMER_ID,
    C.NAME AS CUSTOMER_NAME,
    F.MEDIA_ID,
    M.NAME AS MEDIA_NAME,
    F.CUSTOMER_REF,
    F.SUPPLIER_REF,
    F.INTERNAL_REF,
    F.AROUND_SIZE_MM,
    F.ACROSS_SIZE_MM,
    F.AROUND_UPS,
    F.ACROSS_UPS,
    (F.AROUND_UPS * F.ACROSS_UPS) AS TOTAL_UPS,
    F.AROUND_GAP_MM,
    F.ACROSS_GAP_MM,
    F.CORNER_RADIUS_MM,
    F.SHAPE,
    F.PLATE_WIDTH_MM,
    F.PLATE_LENGTH_MM,
    F.MAX_FEED_STROKE_MM,
    F.TOTAL_CUT_AROUND_MM,
    F.TOTAL_CUT_ACROSS_MM,
    F.CAN_ROTATE,
    CASE 
        WHEN F.CAN_ROTATE = 1 THEN 'BI_DIRECTIONAL'
        ELSE 'FIXED_DIRECTION'
    END AS ROTATION_SUPPORT,
    F.STORAGE_LOCATION,
    F.STORAGE_RACK,
    F.STORAGE_SHELF,
    F.STORAGE_BIN,
    F.STATUS_CODE,
    S.DESCRIPTION AS STATUS_NAME,
    S.BADGE_COLOR,
    F.PURCHASE_DATE,
    F.RECEIVED_DATE,
    F.DIE_MAKER,
    F.TOTAL_IMPRESSIONS,
    F.NOTES,
    F.VERSION,
    F.CREATED_BY,
    F.UPDATED_BY,
    F.CREATED_AT,
    F.UPDATED_AT
FROM FLATBED_DIE F
LEFT JOIN CUSTOMER C ON C.ID = F.CUSTOMER_ID
LEFT JOIN MEDIA M ON M.ID = F.MEDIA_ID
LEFT JOIN DIE_STATUS S ON S.CODE = F.STATUS_CODE;

