/* =============================================================================
   DieVix – Migration V001: Initial Core Schema
   Target: Firebird 5.0
   Encoding: UTF8
============================================================================= */

-- 0. SCHEMA VERSION TRACKING
CREATE TABLE SCHEMA_VERSION (
    VERSION_NUM INTEGER NOT NULL PRIMARY KEY,
    SCRIPT_NAME VARCHAR(100) NOT NULL,
    APPLIED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 1. APPLICATION SETTINGS
CREATE TABLE APP_SETTING (
    SETTING_KEY VARCHAR(50) NOT NULL PRIMARY KEY,
    SETTING_VALUE VARCHAR(255) NOT NULL,
    DESCRIPTION VARCHAR(255)
);

-- 2. CUSTOMER MASTER
CREATE TABLE CUSTOMER (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR(20) NOT NULL UNIQUE,
    NAME VARCHAR(100) NOT NULL,
    CONTACT_PERSON VARCHAR(100),
    PHONE VARCHAR(50),
    EMAIL VARCHAR(100),
    CITY VARCHAR(50),
    NOTES VARCHAR(255),
    IS_ACTIVE SMALLINT DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_CUSTOMER_NAME ON CUSTOMER (NAME);

-- 3. MEDIA SUBSTRATES (Separated Face & Liner layers)
CREATE TABLE MEDIA (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR(30) NOT NULL UNIQUE,
    NAME VARCHAR(100) NOT NULL,
    FACE_MATERIAL VARCHAR(80),
    LINER_MATERIAL VARCHAR(80),
    ADHESIVE_TYPE VARCHAR(50),
    TOTAL_CALIPER_UM INTEGER,
    NOTES VARCHAR(255),
    IS_ACTIVE SMALLINT DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX IDX_MEDIA_NAME ON MEDIA (NAME);

-- 4. DIE STATUS CODES
CREATE TABLE DIE_STATUS (
    CODE VARCHAR(20) NOT NULL PRIMARY KEY,
    DESCRIPTION VARCHAR(50) NOT NULL,
    IS_USABLE SMALLINT DEFAULT 1 NOT NULL,
    BADGE_COLOR VARCHAR(20) DEFAULT 'Green',
    SORT_ORDER INTEGER DEFAULT 0 NOT NULL
);

-- 5. CYLINDER FLEET
CREATE TABLE CYLINDER_SIZE (
    TEETH INTEGER NOT NULL PRIMARY KEY,
    PITCH_UM INTEGER DEFAULT 3175 NOT NULL,
    REPEAT_MM COMPUTED BY (TEETH * PITCH_UM / 1000.0),
    REPEAT_INCH COMPUTED BY (TEETH / 8.0),
    IS_ACTIVE SMALLINT DEFAULT 1 NOT NULL,
    NOTES VARCHAR(100),
    CONSTRAINT CHK_CYL_TEETH CHECK (TEETH > 0),
    CONSTRAINT CHK_CYL_PITCH CHECK (PITCH_UM > 0)
);

-- 6. MACHINE MASTER
CREATE TABLE MACHINE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR(20) NOT NULL UNIQUE,
    NAME VARCHAR(80) NOT NULL,
    MAX_WEB_WIDTH_MM NUMERIC(9,3) NOT NULL,
    MIN_WEB_WIDTH_MM NUMERIC(9,3) DEFAULT 50.000 NOT NULL,
    DEFAULT_MARGIN_MM NUMERIC(9,3) DEFAULT 5.000 NOT NULL,
    PRINT_METHOD VARCHAR(50),
    NOTES VARCHAR(255),
    IS_ACTIVE SMALLINT DEFAULT 1 NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_MACH_WEB_WIDTH CHECK (MAX_WEB_WIDTH_MM >= MIN_WEB_WIDTH_MM)
);

-- 7. MACHINE-CYLINDER COMPATIBILITY ASSIGNMENT
CREATE TABLE MACHINE_CYLINDER (
    MACHINE_ID INTEGER NOT NULL REFERENCES MACHINE(ID) ON DELETE CASCADE,
    TEETH INTEGER NOT NULL REFERENCES CYLINDER_SIZE(TEETH) ON DELETE CASCADE,
    PRIMARY KEY (MACHINE_ID, TEETH)
);

-- 8. DIE MASTER REGISTER
CREATE TABLE DIE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SERIAL_NO VARCHAR(30) NOT NULL UNIQUE,
    CUSTOMER_ID INTEGER REFERENCES CUSTOMER(ID),
    MEDIA_ID INTEGER REFERENCES MEDIA(ID),
    TEETH INTEGER NOT NULL REFERENCES CYLINDER_SIZE(TEETH),
    AROUND_SIZE_MM NUMERIC(9,3) NOT NULL,
    ACROSS_SIZE_MM NUMERIC(9,3) NOT NULL,
    AROUND_UPS INTEGER DEFAULT 1 NOT NULL,
    ACROSS_UPS INTEGER DEFAULT 1 NOT NULL,
    ACROSS_GAP_MM NUMERIC(9,3) DEFAULT 3.000 NOT NULL,
    CORNER_RADIUS_MM NUMERIC(9,3) DEFAULT 2.000 NOT NULL,
    SHAPE VARCHAR(30) DEFAULT 'RECTANGLE' NOT NULL,
    STORAGE_LOCATION VARCHAR(50),
    STATUS_CODE VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL REFERENCES DIE_STATUS(CODE),
    OVERRIDE_REASON VARCHAR(255),
    PURCHASE_DATE DATE,
    DIE_MAKER VARCHAR(100),
    TOTAL_RUN_METRES INTEGER DEFAULT 0,
    NOTES BLOB SUB_TYPE TEXT,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    -- Computed Around Gap in Firebird (dynamically calculated, not redundantly stored)
    COMPUTED_REPEAT_MM COMPUTED BY (TEETH * 3.175),
    COMPUTED_AROUND_GAP_MM COMPUTED BY (
        (TEETH * 3.175 - (AROUND_UPS * AROUND_SIZE_MM)) / NULLIF(AROUND_UPS, 0)
    ),

    CONSTRAINT CHK_DIE_DIMS CHECK (AROUND_SIZE_MM > 0 AND ACROSS_SIZE_MM > 0),
    CONSTRAINT CHK_DIE_UPS CHECK (AROUND_UPS > 0 AND ACROSS_UPS > 0)
);

CREATE INDEX IDX_DIE_DIMS ON DIE (AROUND_SIZE_MM, ACROSS_SIZE_MM, TEETH, AROUND_UPS);
CREATE INDEX IDX_DIE_STATUS ON DIE (STATUS_CODE);
CREATE INDEX IDX_DIE_CUSTOMER ON DIE (CUSTOMER_ID);

-- 9. AUDIT LOG (Tracks status changes and gap overrides)
CREATE TABLE DIE_AUDIT_LOG (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DIE_ID INTEGER REFERENCES DIE(ID) ON DELETE CASCADE,
    ACTION VARCHAR(50) NOT NULL,
    DETAILS VARCHAR(500),
    CHANGED_BY VARCHAR(50) DEFAULT 'SYSTEM' NOT NULL,
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 10. HISTORICAL KEYLINE STAGING (For Safe Cleaning & One-Time Import)
CREATE TABLE STAGING_LEGACY_KEYLINE (
    ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RAW_SERIAL VARCHAR(100),
    RAW_CUSTOMER VARCHAR(150),
    RAW_MEDIA VARCHAR(255),
    RAW_TEETH VARCHAR(50),
    RAW_AROUND_SIZE VARCHAR(50),
    RAW_ACROSS_SIZE VARCHAR(50),
    RAW_AROUND_UPS VARCHAR(50),
    RAW_ACROSS_UPS VARCHAR(50),
    RAW_AROUND_GAP VARCHAR(50),
    RAW_ACROSS_GAP VARCHAR(50),
    RAW_RADIUS VARCHAR(50),
    IMPORT_STATUS VARCHAR(30) DEFAULT 'PENDING',
    CLEANED_DIE_ID INTEGER REFERENCES DIE(ID),
    VALIDATION_NOTE VARCHAR(255)
);

-- 11. CATALOG VIEW
CREATE VIEW V_DIE_CATALOG AS
SELECT
    D.ID,
    D.SERIAL_NO,
    D.CUSTOMER_ID,
    C.NAME AS CUSTOMER_NAME,
    D.MEDIA_ID,
    M.NAME AS MEDIA_NAME,
    D.TEETH,
    D.COMPUTED_REPEAT_MM AS REPEAT_MM,
    (D.TEETH / 8.0) AS REPEAT_INCH,
    D.AROUND_SIZE_MM,
    D.ACROSS_SIZE_MM,
    D.AROUND_UPS,
    D.ACROSS_UPS,
    D.COMPUTED_AROUND_GAP_MM AS AROUND_GAP_MM,
    D.ACROSS_GAP_MM,
    D.CORNER_RADIUS_MM,
    D.SHAPE,
    D.STORAGE_LOCATION,
    D.STATUS_CODE,
    S.DESCRIPTION AS STATUS_NAME,
    S.BADGE_COLOR,
    D.OVERRIDE_REASON,
    CASE 
        WHEN D.COMPUTED_AROUND_GAP_MM >= 3.000 THEN 'APPROVED'
        WHEN D.COMPUTED_AROUND_GAP_MM >= 2.400 THEN 'WARNING_SUB3MM'
        ELSE 'REJECTED_MECHANICAL'
    END AS GAP_POLICY_STATUS,
    D.PURCHASE_DATE,
    D.DIE_MAKER,
    D.TOTAL_RUN_METRES,
    D.NOTES,
    D.CREATED_AT,
    D.UPDATED_AT
FROM DIE D
LEFT JOIN CUSTOMER C ON D.CUSTOMER_ID = C.ID
LEFT JOIN MEDIA M ON D.MEDIA_ID = M.ID
LEFT JOIN DIE_STATUS S ON D.STATUS_CODE = S.CODE;
