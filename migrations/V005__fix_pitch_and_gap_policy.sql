/* =============================================================================
   DieVix – Migration V005: Pitch & Gap Policy Consistency
   Target: Firebird 5.0
   Encoding: UTF8

   Description:
     1. Drop V_DIE_CATALOG dependent view.
     2. Recreate DIE.COMPUTED_REPEAT_MM and DIE.COMPUTED_AROUND_GAP_MM using
        DIE.PITCH_UM (added in V003) instead of hardcoding 3.175.
     3. Fix division scale truncation in CYLINDER_SIZE.REPEAT_MM and REPEAT_INCH
        by casting explicitly to avoid 1-decimal-place truncation.
     4. Recreate V_DIE_CATALOG view reading gap policy thresholds dynamically
        from APP_SETTING (MIN_AROUND_GAP_UM, HARD_BLOCK_GAP_UM) rather than
        hardcoding 3.000 / 2.400 in the view DDL.
============================================================================= */

-- 1. Drop dependent catalog view before altering computed columns
DROP VIEW V_DIE_CATALOG;

-- 2. Drop legacy computed columns on DIE that hardcode 3.175
ALTER TABLE DIE DROP COMPUTED_REPEAT_MM;
ALTER TABLE DIE DROP COMPUTED_AROUND_GAP_MM;

-- 3. Recreate computed columns on DIE using DIE.PITCH_UM with full scale
ALTER TABLE DIE ADD COMPUTED_REPEAT_MM COMPUTED BY (
    CAST((CAST(TEETH AS BIGINT) * PITCH_UM) / 1000.000 AS NUMERIC(18,3))
);

ALTER TABLE DIE ADD COMPUTED_AROUND_GAP_MM COMPUTED BY (
    CAST((CAST((CAST(TEETH AS BIGINT) * PITCH_UM) / 1000.000 AS NUMERIC(18,3)) - (AROUND_UPS * AROUND_SIZE_MM)) / NULLIF(AROUND_UPS, 0) AS NUMERIC(18,3))
);

-- 4. Fix CYLINDER_SIZE computed columns division scale truncation
ALTER TABLE CYLINDER_SIZE DROP REPEAT_MM;
ALTER TABLE CYLINDER_SIZE DROP REPEAT_INCH;

ALTER TABLE CYLINDER_SIZE ADD REPEAT_MM COMPUTED BY (
    CAST((CAST(TEETH AS BIGINT) * PITCH_UM) / 1000.000 AS NUMERIC(18,3))
);

ALTER TABLE CYLINDER_SIZE ADD REPEAT_INCH COMPUTED BY (
    CAST(TEETH / 8.000 AS NUMERIC(18,3))
);

-- 5. Recreate V_DIE_CATALOG reading policy thresholds dynamically from APP_SETTING
CREATE VIEW V_DIE_CATALOG AS
SELECT
    D.ID,
    D.SERIAL_NO,
    D.CUSTOMER_ID,
    C.NAME AS CUSTOMER_NAME,
    D.MEDIA_ID,
    M.NAME AS MEDIA_NAME,
    D.TEETH,
    D.PITCH_UM,
    D.COMPUTED_REPEAT_MM AS REPEAT_MM,
    CAST(D.COMPUTED_REPEAT_MM / 25.400 AS NUMERIC(18,3)) AS REPEAT_INCH,
    D.AROUND_SIZE_MM,
    D.ACROSS_SIZE_MM,
    D.AROUND_UPS,
    D.ACROSS_UPS,
    D.COMPUTED_AROUND_GAP_MM AS AROUND_GAP_MM,
    D.ACROSS_GAP_MM,
    D.CORNER_RADIUS_MM,
    D.SHAPE,
    D.CUT_TYPE,
    D.STORAGE_LOCATION,
    D.STORAGE_RACK,
    D.STORAGE_SHELF,
    D.STORAGE_BIN,
    D.STATUS_CODE,
    S.DESCRIPTION AS STATUS_NAME,
    S.BADGE_COLOR,
    D.OVERRIDE_REASON,
    CASE 
        WHEN D.COMPUTED_AROUND_GAP_MM >= (COALESCE((SELECT CAST(SETTING_VALUE AS NUMERIC(18,3)) FROM APP_SETTING WHERE SETTING_KEY = 'MIN_AROUND_GAP_UM'), 3000.000) / 1000.000) THEN 'APPROVED'
        WHEN (COALESCE((SELECT CAST(SETTING_VALUE AS INTEGER) FROM APP_SETTING WHERE SETTING_KEY = 'HARD_BLOCK_GAP_UM'), 0) > 0)
             AND (D.COMPUTED_AROUND_GAP_MM < (SELECT CAST(SETTING_VALUE AS NUMERIC(18,3)) FROM APP_SETTING WHERE SETTING_KEY = 'HARD_BLOCK_GAP_UM') / 1000.000) THEN 'REJECTED_MECHANICAL'
        WHEN D.COMPUTED_AROUND_GAP_MM < 0.000 THEN 'REJECTED_MECHANICAL'
        ELSE 'WARNING_SUB3MM'
    END AS GAP_POLICY_STATUS,
    D.PURCHASE_DATE,
    D.RECEIVED_DATE,
    D.DIE_MAKER,
    D.SUPPLIER_REF,
    D.TOTAL_RUN_METRES,
    D.DESCRIPTION,
    D.INTERNAL_REF,
    D.CUSTOMER_REF,
    D.NOTES,
    D.VERSION,
    D.CREATED_BY,
    D.CREATED_AT,
    D.UPDATED_BY,
    D.UPDATED_AT
FROM DIE D
LEFT JOIN CUSTOMER C ON D.CUSTOMER_ID = C.ID
LEFT JOIN MEDIA M ON D.MEDIA_ID = M.ID
LEFT JOIN DIE_STATUS S ON D.STATUS_CODE = S.CODE;
