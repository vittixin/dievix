-- 4. Recreate V_DIE_CATALOG view to expose extended fields
CREATE OR ALTER VIEW V_DIE_CATALOG AS
SELECT
    D.ID,
    D.SERIAL_NO,
    D.CUSTOMER_ID,
    C.NAME AS CUSTOMER_NAME,
    D.MEDIA_ID,
    M.NAME AS MEDIA_NAME,
    D.TEETH,
    D.PITCH_UM,
    ((D.TEETH * D.PITCH_UM) / 1000.0) AS REPEAT_MM,
    ((D.TEETH * D.PITCH_UM) / 1000.0 / 25.4) AS REPEAT_INCH,
    D.AROUND_SIZE_MM,
    D.ACROSS_SIZE_MM,
    D.AROUND_UPS,
    D.ACROSS_UPS,
    D.COMPUTED_AROUND_GAP_MM AS AROUND_GAP_MM,
    D.ACROSS_GAP_MM,
    D.CORNER_RADIUS_MM,
    D.SHAPE,
    D.CUT_TYPE,
    D.STORAGE_LOCATION,
    D.STORAGE_RACK,
    D.STORAGE_SHELF,
    D.STORAGE_BIN,
    D.STATUS_CODE,
    S.DESCRIPTION AS STATUS_NAME,
    S.BADGE_COLOR,
    D.OVERRIDE_REASON,
    CASE 
        WHEN D.COMPUTED_AROUND_GAP_MM >= 3.000 THEN 'APPROVED'
        WHEN D.COMPUTED_AROUND_GAP_MM >= 2.400 THEN 'WARNING_SUB3MM'
        ELSE 'REJECTED_MECHANICAL'
    END AS GAP_POLICY_STATUS,
    D.PURCHASE_DATE,
    D.RECEIVED_DATE,
    D.DIE_MAKER,
    D.SUPPLIER_REF,
    D.TOTAL_RUN_METRES,
    D.DESCRIPTION,
    D.INTERNAL_REF,
    D.CUSTOMER_REF,
    D.NOTES,
    D.VERSION,
    D.CREATED_BY,
    D.CREATED_AT,
    D.UPDATED_BY,
    D.UPDATED_AT
FROM DIE D
LEFT JOIN CUSTOMER C ON D.CUSTOMER_ID = C.ID
LEFT JOIN MEDIA M ON D.MEDIA_ID = M.ID
LEFT JOIN DIE_STATUS S ON D.STATUS_CODE = S.CODE;

-- 5. Ensure core status codes ACTIVE and REPAIR exist
UPDATE OR INSERT INTO DIE_STATUS (CODE, DESCRIPTION, IS_USABLE, BADGE_COLOR, SORT_ORDER)
VALUES ('ACTIVE', 'Active / Ready for Press', 1, 'Green', 5) MATCHING (CODE);

UPDATE OR INSERT INTO DIE_STATUS (CODE, DESCRIPTION, IS_USABLE, BADGE_COLOR, SORT_ORDER)
VALUES ('REPAIR', 'Under Repair / Sharpening', 0, 'Orange', 35) MATCHING (CODE);

